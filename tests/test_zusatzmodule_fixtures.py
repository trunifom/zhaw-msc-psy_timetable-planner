def test_bsc_vollstaendig_loads_almost_every_row(bsc_modules):
    # 1182 raw rows, one genuinely has a malformed time value ("11"
    # instead of "HH:MM") in the real source export - this is a real,
    # pre-existing data-quality issue in the actual HS26 catalog, kept
    # intact by the fictionalization (it doesn't touch Datum/von/bis), so
    # this is also an implicit regression test for the "one bad row
    # doesn't sink the whole import" graceful-degradation behaviour
    # documented in data_loader.py's module docstring.
    assert len(bsc_modules) == 1181


def test_bsc_vollstaendig_source_file_has_no_weekday_column(bsc_modules):
    # Sanity-checks the premise of the next test: if this fixture ever
    # gained a Tag column (e.g. from a future regeneration against a
    # different real export), the derivation test below would stop
    # meaning anything and should be revisited.
    raw_df = pd.read_excel(BSC_VOLLSTAENDIG_PATH, header=None, sheet_name="Vorlesungsverzeichnis")
    header_row = [str(v).strip().lower() for v in raw_df.iloc[2].tolist()]
    assert "tag" not in header_row


def test_bsc_vollstaendig_weekday_derived_for_every_row(bsc_modules):
    # Every one of the ~1181 loaded rows must have a real Weekday enum
    # value (not a placeholder) - proves the datum->wochentag derivation
    # (data_loader.py) works across the *entire* real date range, not
    # just a couple of hand-picked dates.
    assert all(isinstance(m.wochentag, Weekday) for m in bsc_modules)
    weekdays_seen = {m.wochentag for m in bsc_modules}
    # The real semester spans weekday and Saturday sessions (see the real
    # Semester column's "VZ"/"TZ" mix) - expect meaningful spread, not
    # e.g. everything accidentally collapsing onto one weekday due to an
    # off-by-one in the derivation.
    assert len(weekdays_seen) >= 5


def test_bsc_vollstaendig_all_rows_tagged_as_zusatzmodul(bsc_modules):
    assert all(m.ist_zusatzmodul is True for m in bsc_modules)


def test_bsc_vollstaendig_ects_defaults_to_zero(bsc_modules):
    # The real Bachelor export has no ECTS column at all - confirms the
    # "ECTS is the only missing required column -> default to 0" rule
    # (data_loader.py) still applies at full scale, not just to the small
    # hand-built fixture.
    assert all(m.ects == 0 for m in bsc_modules)


def test_bsc_vollstaendig_covers_every_real_modulart(bsc_modules):
    # The real catalog's three Modulart values, confirmed via direct
    # inspection of the source export - if fictionalization or loading
    # ever dropped/mangled Modulart, this would catch it.
    assert {m.modultyp for m in bsc_modules} == {"Pflichtmodul", "Spezialtermin", "Wahlpflichtmodul"}


def test_bsc_vollstaendig_contains_a_fully_labeled_parallel_group(bsc_modules):
    # The real catalog's biggest "labeled" parallel-group pattern: 8 rows
    # at the same date/time/Modul-Nr, each with a distinct "- Gruppe X"
    # suffix (a>h) - a student can meaningfully choose between them. This
    # locks in that the fictionalization's per-base-title mapping (see
    # generate_fictional_fixtures.py's split_title_suffix) doesn't merge
    # or lose any of the 8 distinct suffixes.
    by_slot = {}
    for m in bsc_modules:
        by_slot.setdefault((m.datum, m.startzeit, m.endzeit, m.modul_nr), set()).add(m.modulname)
    largest_group = max(by_slot.values(), key=len)
    assert len(largest_group) == 8
    assert all("Gruppe" in name for name in largest_group)


def test_bsc_vollstaendig_contains_undistinguished_parallel_offerings(bsc_modules):
    # The real catalog's OTHER parallel-offering pattern: same date/time/
    # Modul-Nr/Kurs-Nr/title, but with NO distinguishing suffix at all -
    # only the lecturer differs (see docs/planung/KONZEPT-passerelle-
    # zusatzmodule.md section 8, risk 1 - confirmed in ~47% of the real
    # catalog's same-slot multi-lecturer cases). This is what
    # app._has_undistinguished_parallel_offerings() (not covered by this
    # file - see docs/TESTING-README.md "What isn't covered") detects.
    by_slot: dict[tuple, list] = {}
    for m in bsc_modules:
        by_slot.setdefault((m.datum, m.startzeit, m.endzeit, m.modul_nr, m.kurs_nr, m.modulname), []).append(m)
    undistinguished_groups = [rows for rows in by_slot.values() if len({r.dozierende for r in rows}) > 1]
    assert len(undistinguished_groups) > 0
    assert any(len(rows) >= 3 for rows in undistinguished_groups)


def test_bsc_vollstaendig_no_real_lecturer_names_leaked(bsc_modules):
    # A cheap-but-meaningful safety net (not a substitute for actually
    # diffing against the real file, which isn't available in CI/most
    # dev machines - see data/real/'s .gitignore): every fictional
    # lecturer name in this project's convention is "<Surname> <First
    # name>" built from a small closed pool of obviously-invented
    # surnames (see generate_fictional_fixtures.py's _SURNAMES). If a
    # real name ever leaked through, it would almost certainly not start
    # with one of these.
    fictional_surnames = {
        "Muster", "Beispiel", "Demo", "Platzhalter", "Vorlage", "Fiktiv",
        "Testfall", "Musterfrau", "Musterhaft", "Probeweise",
    }
    surnames_seen = {str(m.dozierende).split(" ")[0] for m in bsc_modules if m.dozierende and m.dozierende != "N/A"}
    assert surnames_seen <= fictional_surnames


