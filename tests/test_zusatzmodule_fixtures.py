"""
Tests for the Zusatzmodule/Passerelle feature (see
docs/planung/KONZEPT-passerelle-zusatzmodule.md) against the large-scale
and scenario-specific fixtures in tests/fixtures/, generated by
tests/fixtures/generate_fictional_fixtures.py.

Kept separate from test_data_loader.py/test_scheduler.py (which already
cover the general-purpose loader/conflict pipeline against the original,
smaller fixtures) because this file specifically exercises Zusatzmodule
behaviour at a realistic real-world scale and diversity: the "vollstaendig"
fixtures are full-scale fictionalizations of the actual HS26 Bachelor
(1182 rows) and Master (343 rows) catalogs the feature was built and
verified against, not hand-picked excerpts - so a regression that only
shows up with real-world row counts, real Modulart diversity, or the
real "undistinguished parallel offerings" frequency (see
app._has_undistinguished_parallel_offerings) has a fixture that can
actually catch it.

None of this file's fixtures contain any real person's name or real ZHAW
curriculum content - see generate_fictional_fixtures.py's module
docstring for the fictionalization rules and tests/fixtures/
generate_fictional_fixtures.py itself for how they were produced.
"""

