    # regular Tuesday lectures start on 2026-09-15) - kept intentionally
    # to prove the loader doesn't quietly clip or reorder real dates.
    # 2027-01-19 (not the raw file's true latest date, 2027-02-24) is the
    # latest date among *loaded* modules: the row actually dated
