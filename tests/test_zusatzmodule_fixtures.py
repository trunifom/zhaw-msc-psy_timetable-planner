def _load(path: Path, ist_zusatzmodul: bool = False):
    """Read a fixture the same way app.py's Excel upload branch does
    (header=None, letting data_loader locate the real header row itself)
    and run it through the real loader - never construct ZHAWModule
    objects by hand in this file, since the whole point is exercising the
    full real pipeline against realistic data."""
    raw_df = pd.read_excel(path, header=None, sheet_name="Vorlesungsverzeichnis")
    return load_schedule_from_dataframe(raw_df, ist_zusatzmodul=ist_zusatzmodul)


