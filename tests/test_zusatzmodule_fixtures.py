def test_excel_export_at_full_scale_includes_quelle_column(bsc_modules, msc_modules):
    combined = list(msc_modules) + list(bsc_modules)
    export_df = prepare_timetable_for_export(combined)
    assert len(export_df) == len(combined)
    assert "Quelle" in export_df.columns
    assert (export_df["Quelle"] == "Hauptliste").sum() == len(msc_modules)
    assert (export_df["Quelle"] == "Zusatzmodul").sum() == len(bsc_modules)

    # Doesn't just build the DataFrame - actually renders it to a real
    # .xlsx at ~1500 rows, matching what a Passerelle student with both
    # catalogs fully selected would trigger via render_export_section().
    xlsx_bytes = generate_excel_download(export_df)
    assert xlsx_bytes[:2] == b"PK"
    roundtrip = pd.read_excel(io.BytesIO(xlsx_bytes), sheet_name="Stundenplan")
    assert len(roundtrip) == len(combined)


def test_ics_export_at_full_scale_tags_every_zusatzmodul_row(bsc_modules, msc_modules):
    combined = list(msc_modules) + list(bsc_modules)
    ics_bytes = generate_ics_download(combined, calendar_name="Testkalender")
    ics_text = ics_bytes.decode("utf-8")

    assert ics_text.count("BEGIN:VEVENT") == len(combined)
    # Every module in bsc_modules is ist_zusatzmodul=True (see
    # test_bsc_vollstaendig_all_rows_tagged_as_zusatzmodul), so the
    # "Zusatzmodul (Passerelle)" description line must appear at least
    # once per Bachelor row's event. DESCRIPTION lines are folded (RFC5545,
    # see export._fold_ics_line) and "\n"-escaped within one folded field,
    # so counting exact occurrences would be fragile - presence is enough
    # to prove the tagging logic actually ran at this scale, not just on
    # the 1-2 row hand-built fixtures in test_export.py.
    assert "Zusatzmodul (Passerelle)" in ics_text


# --- Determinism / reproducibility of the generator ----------------------

def test_generated_fixtures_are_internally_consistent_with_each_other(bsc_modules, msc_modules):
    # Same fictional-name pool feeds both catalogs (see
    # generate_fictional_fixtures.py's _FICTIONAL_FULL_NAMES) - a
    # lecturer name appearing in one fixture is not inherently wrong if
    # it also appears in the other (real lecturers can plausibly teach in
    # both programs), but every name in both must still come from the
    # closed fictional surname pool - a stronger, catalog-spanning version
    # of test_bsc_vollstaendig_no_real_lecturer_names_leaked.
    fictional_surnames = {
        "Muster", "Beispiel", "Demo", "Platzhalter", "Vorlage", "Fiktiv",
        "Testfall", "Musterfrau", "Musterhaft", "Probeweise",
    }
    all_surnames = {
        str(m.dozierende).split(" ")[0]
        for m in list(bsc_modules) + list(msc_modules)
        if m.dozierende and m.dozierende != "N/A"
    }
    assert all_surnames <= fictional_surnames


@pytest.mark.skipif(
    not (REAL_BSC_PATH.exists() and REAL_MSC_PATH.exists()),
    reason="data/real/ (git-ignored) not present on this machine - nothing real to compare against.",
)
def test_no_real_module_identifiers_or_titles_leaked_into_fixtures(bsc_modules, msc_modules):
    """
    Extra safety net beyond the closed-surname-pool checks above: on a
    machine that actually has the real files (e.g. the maintainer's,
    never CI - see data/real/'s own .gitignore), directly diff the real
    Modul-Nr/Kurs-Nr/Anlassbezeichnung values against what ended up in the
    committed fixtures. Skipped everywhere else since there's nothing real
    to compare against - the fixtures' safety doesn't depend on this test
    ever running, it's a belt-and-braces check for whoever regenerates
    them next to a newer real export.
    """
    real_bsc = pd.read_excel(REAL_BSC_PATH, sheet_name="Sheet", header=6)
    real_bsc.columns = [str(c).strip() for c in real_bsc.columns]
    real_msc = pd.read_excel(REAL_MSC_PATH, sheet_name=0, header=2)
    real_msc.columns = [str(c).strip() for c in real_msc.columns]

    real_modul_nrs = set(real_bsc["Modul-Nr."].dropna()) | set(real_msc["Modul-Nr."].dropna())
    real_kurs_nrs = set(real_bsc["Kurs-Nr."].dropna()) | set(real_msc["Kurs-Nr."].dropna())
    real_titles = set(real_bsc["Anlassbezeichnung"].dropna()) | set(real_msc["Anlassbezeichnung"].dropna())

    fictional_modules = list(bsc_modules) + list(msc_modules)
    assert not ({m.modul_nr for m in fictional_modules} & real_modul_nrs)
    assert not ({m.kurs_nr for m in fictional_modules} & real_kurs_nrs)
    assert not ({m.modulname for m in fictional_modules} & real_titles)
